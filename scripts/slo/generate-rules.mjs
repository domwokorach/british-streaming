#!/usr/bin/env node
// Generates Prometheus recording + multi-window burn-rate alert rules from slo/slos.json.
// `--check` fails if the committed file is stale (used in CI and tests).
import { readFileSync, writeFileSync } from "node:fs";
import { errorBudgetRatio, loadSlos } from "./lib.mjs";

const OUT = new URL("../../monitoring/prometheus/rules/slo.rules.yml", import.meta.url);
const WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"];

export function render(config = loadSlos()) {
  const days = config.windowDays;
  const lines = ["# GENERATED by scripts/slo/generate-rules.mjs from slo/slos.json — do not edit by hand.", "groups:"];
  for (const slo of config.slos) {
    const expr = (w) => `1 - (${slo.sli.good.replaceAll("$WINDOW", w)}) / (${slo.sli.total.replaceAll("$WINDOW", w)})`;
    lines.push(`  - name: slo-${slo.name}-recording`, "    interval: 30s", "    rules:");
    for (const w of [...WINDOWS, `${days}d`]) {
      lines.push(`      - record: slo:${slo.name}:error_ratio_rate${w}`, `        expr: ${expr(w)}`, "        labels:", `          service: ${config.service}`);
    }
    lines.push(
      `      - record: slo:${slo.name}:error_budget_remaining_ratio`,
      `        expr: 1 - slo:${slo.name}:error_ratio_rate${days}d / ${errorBudgetRatio(slo.objective)}`,
      "        labels:",
      `          service: ${config.service}`,
      `      - record: slo:${slo.name}:objective_ratio`,
      `        expr: ${slo.objective / 100}`,
      "        labels:",
      `          service: ${config.service}`
    );
    lines.push(`  - name: slo-${slo.name}-burn-alerts`, "    rules:");
    for (const a of config.burnRateAlerts) {
      const threshold = +(a.burnRate * errorBudgetRatio(slo.objective)).toPrecision(6);
      lines.push(
        `      - alert: ErrorBudgetBurn_${slo.name}_${a.long}`,
        `        expr: slo:${slo.name}:error_ratio_rate${a.long} > ${threshold} and slo:${slo.name}:error_ratio_rate${a.short} > ${threshold}`,
        `        for: ${a.severity === "page" ? "2m" : "15m"}`,
        "        labels:",
        `          severity: ${a.severity}`,
        `          slo: ${slo.name}`,
        `          service: ${config.service}`,
        "        annotations:",
        `          summary: "${slo.name} SLO burning ${a.burnRate}x budget (${a.long} and ${a.short} windows)"`,
        `          description: "${a.note}. Objective ${slo.objective}% over ${days}d."`,
        "          runbook_url: docs/runbooks/error-budget-burn.md"
      );
    }
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const next = render();
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== next) { console.error("slo.rules.yml is stale. Run: node scripts/slo/generate-rules.mjs"); process.exit(1); }
    console.log("slo.rules.yml is up to date");
  } else { writeFileSync(OUT, next); console.log(`wrote ${OUT.pathname}`); }
}
